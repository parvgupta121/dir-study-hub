-- DIR Study Hub shared database. Run in Supabase SQL Editor.
create table if not exists public.private_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  chapter_id integer not null check (chapter_id between 1 and 17),
  completed jsonb not null default '{}'::jsonb,
  updated_at timestamptz not null default now(),
  primary key (user_id, chapter_id)
);
create table if not exists public.community_notes (
  id bigint generated by default as identity primary key,
  chapter_id integer not null check (chapter_id between 1 and 17),
  content text not null check (char_length(trim(content)) between 1 and 5000),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null,
  created_at timestamptz not null default now()
);
create table if not exists public.note_votes (
  note_id bigint not null references public.community_notes(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (note_id,user_id)
);
alter table public.private_progress enable row level security;
alter table public.community_notes enable row level security;
alter table public.note_votes enable row level security;
create policy "Read own progress" on public.private_progress for select using (auth.uid() = user_id);
create policy "Insert own progress" on public.private_progress for insert with check (auth.uid() = user_id);
create policy "Update own progress" on public.private_progress for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Read community notes" on public.community_notes for select using (true);
create policy "Signed-in users add notes" on public.community_notes for insert to authenticated with check (auth.uid() = author_id);
create policy "Authors delete own notes" on public.community_notes for delete to authenticated using (auth.uid() = author_id);
create policy "Read note votes" on public.note_votes for select using (true);
create policy "Users add own votes" on public.note_votes for insert to authenticated with check (auth.uid() = user_id);
create policy "Users remove own votes" on public.note_votes for delete to authenticated using (auth.uid() = user_id);
grant select, insert, update, delete on public.private_progress to authenticated;
grant select, insert, delete on public.community_notes to anon, authenticated;
grant select, insert, delete on public.note_votes to anon, authenticated;
grant usage, select on sequence public.community_notes_id_seq to authenticated;
